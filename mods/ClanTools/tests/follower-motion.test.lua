local M=dofile('mods/ClanTools/Scripts/follower_motion.lua')
local count=0
local function test(name,fn)fn();count=count+1;print('PASS '..name)end
local function p(x,y,z)return{X=x,Y=y,Z=z or 0}end
test('two companions have distinct staggered arrival positions',function()
 local a=M.new(1).plan(p(0,0),p(1,0),p(-300,0),{},150,.2)
 local b=M.new(2).plan(p(0,0),p(1,0),p(-300,0),{},150,.2)
 assert(a.goal.Y<0 and b.goal.Y>0 and b.goal.X<a.goal.X)
 assert((a.goal.X-b.goal.X)^2+(a.goal.Y-b.goal.Y)^2>150^2)
end)
test('turning in place preserves the settled formation',function()
 local a=M.new(1);local first=a.plan(p(0,0),p(1,0),p(-150,-75),{},150,.2)
 for _,f in ipairs({p(0,1),p(-1,0),p(0,-1)})do local r=a.plan(p(0,0),f,p(-150,-75),{},150,.2);assert(r.stop and r.goal.X==first.goal.X and r.goal.Y==first.goal.Y)end
end)
test('right angle turns follow traveled route instead of jumping behind new heading',function()
 local a=M.new(1);a.plan(p(0,0),p(1,0),p(-200,0),{},150,.2)
 for x=20,200,20 do a.plan(p(x,0),p(1,0),p(0,-75),{},150,.2)end
 local r=a.plan(p(200,20),p(0,1),p(100,-75),{},150,.2)
 assert(math.abs(r.center.Y)<.001 and r.center.X>0 and r.center.X<200)
end)
test('arrival has hysteresis and bounded smooth approach speed',function()
 local a=M.new(1);assert(a.plan(p(0,0),p(1,0),p(-150,-75),{},150,.2).stop)
 assert(a.plan(p(0,0),p(1,0),p(-200,-75),{},150,.2).stop)
 local far=a.plan(p(0,0),p(1,0),p(-500,-75),{},150,.2);assert(not far.stop and far.speed<=600)
 local near=a.plan(p(0,0),p(1,0),p(-195,-75),{},150,.2);assert(not near.stop and near.speed<far.speed)
end)
test('overlapping companions choose opposing separation directions',function()
 local a=M.new(1).plan(p(0,0),p(1,0),p(-200,0),{p(-200,0)},150,.2)
 local b=M.new(2).plan(p(0,0),p(1,0),p(-200,0),{p(-200,0)},150,.2)
 assert(a.goal.Y< -75 and b.goal.Y>75)
end)
test('teleports discard old trail and produce a nearby new target',function()
 local a=M.new(1);a.plan(p(0,0),p(1,0),p(-200,0),{},150,.2)
 local r=a.plan(p(10000,10000),p(0,1),p(9900,10000),{},150,.2)
 assert(math.abs(r.goal.X-10000)<500 and math.abs(r.goal.Y-10000)<500)
end)
print(count..' follower movement scenarios passed.')
